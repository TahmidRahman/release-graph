import { readFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const read = (f) => readFileSync(resolve(here, 'client', f), 'utf8');

const esc = (s) => String(s == null ? '' : s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
const day = (t) => new Date(t * 1000).toISOString().slice(0, 10);

function branchBar(model) {
  const bad = model.branches.filter((b) => model.integration.some((n) => b.status[n] === 'absent') && b.ahead > 0);
  if (!bad.length) return '';
  const chips = bad.slice(0, 40).map((b) => {
    const where = model.integration.filter((n) => b.status[n] === 'absent').join(', ');
    return `<span class="bchip" title="${esc(b.ahead)} commit(s) not on ${esc(where)}">`
      + `<code>${esc(b.name)}</code> <em>+${b.ahead}</em> <s>${esc(where)}</s></span>`;
  }).join('');
  return `<div id="branchbar"><strong>${bad.length} release branch${bad.length === 1 ? '' : 'es'} still carrying unmerged commits</strong>${chips}`
    + (bad.length > 40 ? `<span class="bchip">+${bad.length - 40} more</span>` : '')
    + `<button class="bclose" onclick="this.parentNode.remove()">&times;</button></div>`;
}

